use crate::app_info::GET_APP_INFO_COMMAND;

pub fn typescript_bindings() -> String {
    format!(
        r#"// Generated by lattice-core. Do not edit by hand.

export const APP_COMMANDS = {{
  getAppInfo: '{get_app_info_command}'
}} as const;

export type AppCommand = (typeof APP_COMMANDS)[keyof typeof APP_COMMANDS];

export type NativeAppRuntime = 'tauri';

export type BuildProfile = 'debug' | 'release';

export interface NativeAppInfo {{
  readonly name: string;
  readonly version: string;
  readonly buildProfile: BuildProfile;
  readonly runtime: NativeAppRuntime;
  readonly target: string;
}}

export interface AppError {{
  readonly code: string;
  readonly message: string;
  readonly recoverable: boolean;
  readonly correlationId?: string;
}}
"#,
        get_app_info_command = GET_APP_INFO_COMMAND
    )
}

#[cfg(test)]
mod tests {
    use super::typescript_bindings;
    use std::fs;
    use std::path::PathBuf;

    #[test]
    fn committed_typescript_bindings_match_rust_contract() -> Result<(), Box<dyn std::error::Error>>
    {
        let bindings_path =
            PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../packages/types/src/generated.ts");
        let committed_bindings = fs::read_to_string(bindings_path)?;

        assert_eq!(committed_bindings, typescript_bindings());
        Ok(())
    }
}
