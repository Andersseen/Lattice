#[cfg(test)]
mod tests {
    use super::typescript_bindings;
    use std::fs;
    use std::path::PathBuf;

    #[test]
    fn committed_typescript_bindings_match_rust_contract() -> Result<(), Box<dyn std::error::Error>>
    {
        let bindings_path =
            PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../packages/types/src/generated.ts");
        let committed_bindings = fs::read_to_string(bindings_path)?;

        assert_eq!(committed_bindings, typescript_bindings());
        Ok(())
    }
}
